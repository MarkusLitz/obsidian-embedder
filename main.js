    const typeInfo = getFileTypeInfo(fileName);
    const category = typeInfo ? typeInfo.category : "document";
    const lineStart = countLinesBefore(content, matchStart);
    occurrences.push({
      fileId,
      fileName,
      notePath,
      noteName,
      lineStart,
      lineEnd: lineStart,
      charStart: matchStart,
      charEnd: matchEnd,
      category,
      showTitle: Boolean(linkMatch[1])
    });
