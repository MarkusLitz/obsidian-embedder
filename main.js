async function removeEmbedFromNote(app, file, target) {
  let removedCount = 0;
  await app.vault.process(file, (content) => {
    const occurrences = scanNoteContent(content, file.path, file.basename);
    const matching = occurrences.filter((occ) => {
      if (occ.fileId !== target.fileId) {
        return false;
      }
      if (target.removeAllForFileId) {
        return true;
      }
      if (target.charStart !== void 0 && occ.charStart === target.charStart) {
        return true;
      }
      if (target.lineStart !== void 0 && occ.lineStart === target.lineStart) {
        return true;
      }
      return target.charStart === void 0 && target.lineStart === void 0;
    });
    if (matching.length === 0) {
      return content;
    }
    const sortedDesc = [...matching].sort((a, b) => b.charStart - a.charStart);
    let updated = content;
    for (const occ of sortedDesc) {
      let start = occ.charStart;
      let end = occ.charEnd;
      if (updated.slice(end, end + 2) === "\r\n") {
        end += 2;
        if (updated.slice(end, end + 2) === "\r\n") {
          end += 2;
        }
      } else if (updated[end] === "\n") {
        end += 1;
        if (updated[end] === "\n") {
          end += 1;
        }
      } else if (start > 0 && updated[start - 1] === "\n") {
        start -= 1;
        if (start > 0 && updated[start - 1] === "\r") {
          start -= 1;
        }
      }
      updated = updated.slice(0, start) + updated.slice(end);
      removedCount++;
    }
    return updated;
  });
  return removedCount;
}
